import assert from 'node:assert/strict';
import {createWorkflow,applyServiceCommand as apply,workflowCare} from '@/lib/service-workflow/model';
import {reconcileRecommendations} from '@/lib/service-workflow/reconciliation';
const now=new Date('2026-10-13T04:00:00Z');
const tests=['one','two','three'].map(id=>({id,title:`Lab ${id}`,method:'lab' as const,preparation:'',source:'demo'}));
let w=apply(createWorkflow(tests,now),{type:'book',testIds:tests.map(t=>t.id),at:'2026-10-13T09:00:00+04:00',mode:'home',address:'Hanrapetutyan 4a, 15'},now);
const command={type:'record-provider-preparation',bookingId:w.bookings[0].id,provider:'Demo lab coordinator',instructions:'Instructions received from the fictional provider. Bring your booking reference.'} as const;
assert.throws(()=>apply(w,command,now),/operations/i);
const before=structuredClone(w);
w=apply(w,command,now,{role:'admin',id:'ops-demo'});
assert.equal(w.bookings[0].providerPreparation?.instructions,command.instructions);
assert.equal(w.bookings[0].providerPreparation?.recordedBy,'ops-demo');
assert.equal(before.bookings[0].providerPreparation,undefined);
assert.deepEqual(w.receivedTestIds,[]);
assert.deepEqual(w.publication,before.publication);
assert.equal(workflowCare(w,[],false).tests[0].preparation,command.instructions);
assert.equal(workflowCare(w,[],false).appointments[0].status,'requested');
const cancelled=apply(w,{type:'cancel',bookingId:command.bookingId},now);
assert.throws(()=>apply(cancelled,command,now,{role:'admin',id:'ops-demo'}),/current booking/i);
const review={...w,bookings:w.bookings.map(b=>({...b,review:{reason:'Changed',changedTestIds:['three']}}))};
assert.throws(()=>apply(review,command,now,{role:'admin',id:'ops-demo'}),/current booking/i);
const replacement=apply(w,{type:'book',testIds:tests.map(t=>t.id),at:'2026-10-14T09:00:00+04:00',mode:'home',address:'Different address',replacingId:command.bookingId},now);
assert.equal(replacement.bookings[1].providerPreparation,undefined);
assert.equal(workflowCare(replacement,[],false).appointments[0].status,'requested');
assert.throws(()=>apply(w,{...command,provider:' '},now,{role:'admin',id:'ops-demo'}));
console.log('Booking preparation model checks passed');

const changed=reconcileRecommendations(w,[tests[0],tests[1]],true,2,'changed-context',now);
assert.equal(changed.bookings[0].providerPreparation,undefined);
assert.equal(changed.bookings[0].preparationHistory?.length,1);
const kept=apply(changed,{type:'confirm-booking',bookingId:command.bookingId,testIds:['one','two']},now);
assert.equal(kept.bookings[1].providerPreparation,undefined);
assert.deepEqual(kept.bookings[1].preparationHistory,[]);
