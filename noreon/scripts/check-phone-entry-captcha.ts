import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import * as React from 'react';
import * as jsx from 'react/jsx-runtime';
import {act, create, type ReactTestRenderer} from 'react-test-renderer';
import {normalizePhone,armenianNationalDigits,armenianPhoneFromNational,foreignInternationalNumber} from '@/lib/patient/validation';
import {tx} from '@/lib/patient/copy';
const continuePathModule=await import('@/lib/patient/continue-path');
// Exercise the actual entry component. Only external CAPTCHA, actions, navigation,
// and the countdown clock are replaced; no SMS is sent by this regression.
(globalThis as {IS_REACT_ACT_ENVIRONMENT?:boolean}).IS_REACT_ACT_ENVIRONMENT=true;
let tick:(()=>void)|undefined;
let nextToken='initial-token';
let rejectCaptcha=false;
const sends:Array<{phone:string;token?:string}>=[];
const verifies:Array<{phone:string;code:string}>=[];
let result={ok:true};
// Sign-in ends in a full load, which binds the tab to the account (QA a6-01).
let destination='';
let focusedInputs=0, disabledFocusAttempts=0;
const FakeCaptcha=React.forwardRef(function Captcha(props:Record<string,unknown>,ref:React.ForwardedRef<unknown>){
 React.useImperativeHandle(ref,()=>({resetCaptcha(){},execute:async()=>{if(rejectCaptcha) throw Error('challenge-closed');return {response:nextToken,key:'fixture'};}}));
 const initialReady = React.useRef(props.onReady as (()=>void)|undefined);
 React.useEffect(()=>{initialReady.current?.();},[]);
 return React.createElement('captcha',props);
});
const exports:Record<string,unknown>={};
const code=ts.transpileModule(readFileSync('components/patient/phone-entry.tsx','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}}).outputText;
vm.runInNewContext(code,{exports,window:{location:{replace:(path:string)=>{destination=path;}}},process:{env:{NEXT_PUBLIC_PATIENT_DEMO:'false',NEXT_PUBLIC_HCAPTCHA_SITE_KEY:'fixture'}},setTimeout:(fn:()=>void)=>{tick=fn;return 1;},clearTimeout(){tick=undefined;},require:(name:string)=>{
 if(name==='react')return React;
 if(name==='react/jsx-runtime')return jsx;
 if(name==='@hcaptcha/react-hcaptcha')return {default:FakeCaptcha};
 if(name==='next/navigation')return {useRouter:()=>({})};
 if(name.endsWith('/continue-path'))return continuePathModule;
 if(name.endsWith('/patient/actions'))return {requestPhoneCode:async(phone:string,token?:string)=>{sends.push({phone,token});return result;},verifyPhoneCode:async(phone:string,code:string)=>{verifies.push({phone,code});return result;}};
 if(name.endsWith('/validation'))return {normalizePhone,armenianNationalDigits,armenianPhoneFromNational,foreignInternationalNumber};
 if(name.endsWith('/copy'))return {tx};
 if(name.endsWith('/transport'))return {safeRequest:async(fn:()=>unknown)=>fn(),lockUnavailableMessage:()=>''};
 if(name.endsWith('/patient-shell'))return {PatientShell:({children}:{children:React.ReactNode})=>React.createElement('main',{},children)};
 if(name.endsWith('/onboarding-steps'))return {OnboardingSteps:({step}:{step:number})=>React.createElement('div',{'data-onboarding-step':step})};
 if(name.endsWith('/button'))return {Button:({children,variant,...props}:{children:React.ReactNode;variant?:string})=>{void variant;return React.createElement('button',props,children);}};
 if(name.endsWith('/input'))return {Input:(props:object)=>React.createElement('input',props)};
 if(name.endsWith('/label'))return {Label:(props:object)=>React.createElement('label',props)};
 throw Error(name);
}});
let view:ReactTestRenderer;
await act(async()=>{view=create(React.createElement(exports.PhoneEntry as React.ComponentType<{initialLocale:string;siteKey:string}>,{initialLocale:'en',siteKey:'fixture'}),{createNodeMock:element=>element.type==='input'?{focus(){if(root().findByType('input').props.disabled)disabledFocusAttempts++;else focusedInputs++;}}:element.type==='h1'?{focus(){}}:null});});
const root=()=>view!.root;
const button=(label:string)=>root().findAllByType('button').find(b=>b.children.join('')===label)!;
const submit=async()=>act(async()=>root().findByType('form').props.onSubmit({preventDefault(){}}));
assert.ok(button('Continue'),'Welcome has one clear Continue action');
assert.equal(root().findAllByType(FakeCaptcha).length,0,'Welcome has no CAPTCHA');
assert.equal(sends.length,0);
await act(async()=>root().findByType('input').props.onChange({target:{value:'wrong'}}));
await submit();
assert.equal(root().findAllByType(FakeCaptcha).length,0,'Invalid phone never opens CAPTCHA or sends');
assert.match(root().findByProps({role:'alert'}).children.join(''),/Enter the 8 digits after \+374/);
assert.equal(root().findByType('input').props.value,'','Letters never reach the national-number field');
await act(async()=>root().findByType('input').props.onChange({target:{value:'+1 555 123 4567'}}));
assert.equal(root().findByType('input').props.value,'','A foreign number is not read as Armenian digits');
assert.match(root().findByProps({role:'alert'}).children.join(''),/Armenian \(\+374\) numbers only/);
await act(async()=>root().findByType('input').props.onChange({target:{value:'+37499000000'}}));
assert.equal(root().findByType('input').props.value,'99000000','A pasted +374 leaves only the national digits');
await submit();
assert.equal(sends.length,0,'Continue must not request SMS');
assert.equal(root().findByType(FakeCaptcha).props.size,'normal','CAPTCHA appears only after Continue');
assert.equal(button('Send verification code').props.disabled,true,'Send requires a CAPTCHA token');
await act(async()=>root().findByType(FakeCaptcha).props.onVerify(nextToken));
await act(async()=>root().findByType(FakeCaptcha).props.onExpire());
assert.equal(button('Send verification code').props.disabled,true,'Expired CAPTCHA cannot send');
await act(async()=>root().findByType(FakeCaptcha).props.onVerify(nextToken));
await submit();
assert.equal(sends.length,1);
assert.equal(sends[0].phone,'+37499000000','A pasted +374 number is sent once, in E.164');
assert.equal(sends[0].token,'initial-token');
assert.equal(focusedInputs,1,'The code field receives focus after it is enabled');
assert.equal(disabledFocusAttempts,0,'Focus never targets a disabled field');
assert.equal(root().findAllByType(FakeCaptcha).filter(c=>c.props.size!=='invisible').length,0,'Code entry must not show another CAPTCHA checkbox');
assert.equal(button('Verify and continue').props.disabled,true);
result={ok:false};
await act(async()=>root().findByType('input').props.onChange({target:{value:'000000'}}));
assert.equal(verifies.length,0,'With CAPTCHA on, the sixth digit waits for Verify (unchanged flow)');
await submit();
assert.equal(destination,'');
assert.match(root().findByProps({role:'alert'}).children.join(''),/invalid or expired/);
assert.equal(sends.length,1,'Rejected code does not request another SMS');
result={ok:true};
await act(async()=>root().findByType('input').props.onChange({target:{value:'123456'}}));
await submit();
assert.equal(verifies.length,2,'Code confirmation does not execute CAPTCHA or send SMS');
assert.equal(sends.length,1);
assert.equal(destination,'/patient/dashboard');
for(let i=0;i<60;i++)await act(async()=>tick?.());
assert.equal(button('Resend code').props.disabled,false,'Resend becomes available without asking for a checkbox');
nextToken='resend-token';
await act(async()=>button('Resend code').props.onClick());
assert.equal(sends.length,2);
assert.equal(sends[1].token,'resend-token','Resend supplies a fresh single-use token');
assert.equal(root().findByType('input').props.value,'','Resend clears the old code');
for(let i=0;i<60;i++)await act(async()=>tick?.());
rejectCaptcha=true;
await act(async()=>button('Resend code').props.onClick());
assert.equal(sends.length,2,'Cancelled/failed CAPTCHA must not send an unprotected request');
assert.match(root().findByProps({role:'alert'}).children.join(''),/security check/i);
rejectCaptcha=false;
await act(async()=>button('Change number').props.onClick());
assert.equal(root().findAllByType(FakeCaptcha).length,0,'Changing number returns to the clean welcome');
await submit();
assert.equal(button('Send verification code').props.disabled,true,'Changing number cannot reuse the consumed token');
result={ok:false};
await act(async()=>root().findByType(FakeCaptcha).props.onVerify('retry-token'));
await submit();
assert.equal(button('Send verification code').props.disabled,true,'Failed delivery also consumes the token');
assert.match(root().findByProps({role:'alert'}).children.join(''),/couldn’t send/);
await act(async()=>view!.unmount());
console.log('Phone entry: single visible CAPTCHA, verification without challenge, fresh-token resend, cancellation, number change and delivery failure passed (external boundaries mocked).');
