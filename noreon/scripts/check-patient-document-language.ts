import assert from 'node:assert/strict';
import {createElement} from 'react';
import {create,act} from 'react-test-renderer';
const {PatientDocumentLanguage} = await import('@/components/patient/document-language').catch(()=>({PatientDocumentLanguage:null}));
assert.ok(PatientDocumentLanguage,'Patient document language synchronization must exist');
Object.defineProperty(globalThis,'IS_REACT_ACT_ENVIRONMENT',{value:true,configurable:true});
const root={lang:'en'};
Object.defineProperty(globalThis,'document',{value:{documentElement:root},configurable:true});
let view!:ReturnType<typeof create>;
await act(async()=>{view=create(createElement(PatientDocumentLanguage,{locale:'hy'}));});
assert.equal(root.lang,'hy','Initial patient HY mount changes actual document element');
await act(async()=>{view.update(createElement(PatientDocumentLanguage,{locale:'en'}));});
assert.equal(root.lang,'en','Locale-only client update changes document language');
await act(async()=>{view.update(createElement(PatientDocumentLanguage,{locale:'hy'}));});
assert.equal(root.lang,'hy');
await act(async()=>view.unmount());
assert.equal(root.lang,'en','Leaving patient routes restores public marketing language');
await act(async()=>{view=create(createElement(PatientDocumentLanguage,{locale:'hy'}));});
assert.equal(root.lang,'hy','Fresh remount/reload applies saved HY again');
await act(async()=>view.unmount());
delete (globalThis as {document?:unknown}).document;
console.log('Document language mount, EN/HY updates, cleanup and remount passed (DOM boundary simulated).');
