/** Chat host safety checks. Real page actions and controls have separate checks;
 * this runs the host hooks with IO and child forms replaced, without secrets. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import React from 'react';
import * as jsx from 'react/jsx-runtime';
import {act,create,type ReactTestRenderer} from 'react-test-renderer';
import {renderToStaticMarkup} from 'react-dom/server';
import {BookingRefreshContext} from '@/components/real-booking/recovery-context';
import {MemberContactLine} from '@/components/staff/member-contact';
import * as staffCopy from '@/lib/staff/staff-locale-copy';
import type {AdminMemberBookings} from '@/lib/admin-chat/card-contracts';
import type {MemberSearchPage} from '@/lib/staff/member-search-schema';

Object.assign(globalThis,{IS_REACT_ACT_ENVIRONMENT:true});
const member='a1000000-0000-4000-8000-000000000001';
const page:MemberSearchPage={rows:[{id:member,name:'Example member',revision:1,doctorId:null,nurseId:null,createdAt:'2026-11-01T12:00:00Z',bookingCounts:{requested:0,providerProposed:0,confirmed:1,changePending:0}}],hasMore:false,nextCursor:null};
let data:AdminMemberBookings={memberId:member,name:'Current member',enabled:true,contact:{phone:'+37499123456',telegramLinked:false},requests:[],pilot:{available:false,unavailableReason:'source-unavailable',program:[],offers:[],appointments:[]}};
let reads=0,writes=0,failRead=false,release:(()=>void)|undefined;
let writeResult:{ok:boolean;code:'unknown'|'saved';outcomeUnknown?:boolean}={ok:false,code:'unknown',outcomeUnknown:true};
const requests:unknown[][]=[];
const searches:unknown[]=[];
const write=async(...args:unknown[])=>{writes++;requests.push(args);if(release===undefined)await new Promise<void>(r=>{release=r;});return {access:'allowed' as const,result:writeResult};};
const server={readAdminMemberBookings:async()=>{reads++;if(failRead)throw Error('Fixture read outage');return {access:'allowed' as const,result:data};},searchAdminCareMembers:async(input:unknown)=>{searches.push(input);return {access:'allowed' as const,result:{ok:true,page}};},...Object.fromEntries(['changeAdminAppointment','cancelAdminAppointment','startAdminAppointmentNotice','retryAdminAppointmentNotice','reconcileAdminAppointmentNotice','adminProviderBookingCommand'].map(name=>[name,write]))};
const Pilot=(props:Record<string,unknown>)=>React.createElement('div',{'data-pilot':true},...['changeAction','cancelAction','startAction','retryAction','recoveryAction'].map(name=>React.createElement('button',{key:name,onClick:()=> (props[name] as (...args:unknown[])=>Promise<unknown>)({ok:false},new FormData())},name)));
const Provider=(props:Record<string,unknown>)=>React.createElement('button',{onClick:()=> (props.action as (...args:unknown[])=>Promise<unknown>)({ok:false,message:''},new FormData())},'provider');
const deps:Record<string,unknown>={react:React,'react/jsx-runtime':jsx,'@/components/real-booking/pilot-staff':{PilotStaffBooking:Pilot},'@/components/real-booking/staff':{RealStaffBooking:Provider},'@/components/real-booking/recovery-context':{BookingRefreshContext},'@/components/staff/member-contact':{MemberContactLine},'@/lib/admin-chat/card-actions':server,'@/lib/staff/staff-locale-copy':staffCopy};
const out:Record<string,unknown>={};
new vm.Script(ts.transpileModule(readFileSync('components/staff/admin-booking-card.tsx','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}}).outputText).runInNewContext({exports:out,crypto,require:(name:string)=>{assert.ok(name in deps,name);return deps[name];}});
const Card=out.AdminBookingCard as typeof import('../components/staff/admin-booking-card').AdminBookingCard;
const unwrap=async<T,>(request:()=>Promise<{access:'allowed';result:T}|{access:'off'|'denied'}>)=>{const response=await request();if(response.access!=='allowed')throw Error('Refused');return response.result;};
for(const locale of ['en','hy','ru'] as const){
 const html=renderToStaticMarkup(React.createElement(Card,{page,locale,unwrap}));
 assert.ok(html.includes(locale==='en'?'Bookings and contact':locale==='hy'?'Ամրագրումներ և կապ':'Записи и контакты'));
 if(locale==='ru')assert.ok(!/[Ա-և]/.test(html));
 const contact=renderToStaticMarkup(React.createElement(MemberContactLine,{contact:data.contact,locale}));
 assert.ok(contact.includes('tel:+37499123456'));
 assert.ok(contact.includes(locale==='en'?'Write on Telegram':locale==='hy'?'Գրել Telegram-ով':'Написать в Telegram'));
}
let tree!:ReactTestRenderer;
await act(async()=>{tree=create(React.createElement(Card,{page:{rows:[],hasMore:false,nextCursor:null},locale:'en',unwrap}));});
const button=(label:string)=>tree.root.findAllByType('button').find(b=>b.children.join('')===label)!;
assert.equal(searches.length,0,'Opening the card never starts a member search');
assert.equal(reads,0,'Opening the card does not read another member');
assert.ok(JSON.stringify(tree.toJSON()).includes('Search for a member'));
await act(async()=>tree.root.findByType('input').props.onChange({target:{value:'Example'}}));
assert.equal(searches.length,0,'Typing alone does not search');
await act(async()=>tree.root.findByType('form').props.onSubmit({preventDefault(){}}));
assert.equal(JSON.stringify(searches),JSON.stringify([{query:'Example',cursor:null}]),'Only an explicit search reads the member list');
await act(async()=>{button('Example member').props.onClick();button('Example member').props.onClick();});
assert.equal(reads,1,'Same-event member selection reads once');
assert.ok(JSON.stringify(tree.toJSON()).includes('Current member'));
await act(async()=>{button('cancelAction').props.onClick();button('provider').props.onClick();button('Check current details').props.onClick();});
assert.equal(writes,1,'Competing booking/provider operations dispatch once');
assert.equal(reads,1,'Refresh cannot race an in-flight write');
await act(async()=>{release!();});
assert.equal(requests[0][0],member);
assert.ok(tree.root.findAllByType('fieldset').some(f=>f.props.disabled),'Unknown result locks all booking forms');
assert.equal(reads,1,'Unknown outcomes require an explicit reread');
assert.ok(JSON.stringify(tree.toJSON()).includes('An unknown result must not be sent again.'));
const oldPilot=tree.root.findByType(Pilot);
failRead=true;
await act(async()=>button('Check current details').props.onClick());
assert.equal(writes,1,'Refresh never resends');
assert.equal(tree.root.findByType(Pilot),oldPilot,'Read failure preserves uncertain form state');
assert.ok(JSON.stringify(tree.toJSON()).includes('These details could not load'));
await act(async()=>button('changeAction').props.onClick());
assert.equal(writes,1,'A failed refresh cannot unlock another operation');
failRead=false;
await act(async()=>button('Check current details').props.onClick());
assert.notEqual(tree.root.findByType(Pilot),oldPilot,'Successful authoritative read creates a new form session');
await act(async()=>button('changeAction').props.onClick());
assert.equal(writes,2);
await act(async()=>button('Check current details').props.onClick());
for(const action of ['changeAction','cancelAction','provider']){
 writeResult={ok:true,code:'saved'};
 data={...data,name:`Fresh after ${action}`};
 const before:number=reads;
 await act(async()=>button(action).props.onClick());
 assert.equal(reads,before+1,'Successful write automatically reads current booking details');
 assert.ok(JSON.stringify(tree.toJSON()).includes(`Fresh after ${action}`),'The current state replaces the earlier card');
 assert.ok(tree.root.findAllByType('fieldset').every(f=>!f.props.disabled),'Fresh successful read unlocks controls');
}
failRead=true;
await act(async()=>button('cancelAction').props.onClick());
assert.ok(tree.root.findAllByType('fieldset').some(f=>f.props.disabled),'A failed post-write read keeps controls locked');
assert.ok(JSON.stringify(tree.toJSON()).includes('These details could not load'));
failRead=false;
data={...data,pilot:null,requests:null,contact:null};
await act(async()=>button('Check current details').props.onClick());
const html=JSON.stringify(tree.toJSON());
assert.ok(html.includes('Visit details are unavailable.'));
assert.ok(html.includes('Provider requests are unavailable.'));
assert.ok(html.includes('Contact details are unavailable.'));
assert.equal(tree.root.findAllByType(Pilot).length,0,'Unavailable is never an empty booking list');
await act(async()=>tree.unmount());
console.log('Admin booking host: three locales, audited contact presentation, duplicate selection/commands, cross-form lock, refresh/write race, unknown result, failed reread preservation and per-source outages passed (mocked IO).');
