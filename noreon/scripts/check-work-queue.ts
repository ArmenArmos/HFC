import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createWorkflow } from '@/lib/service-workflow/model';
import { serviceNextAction } from '@/lib/service-workflow/next-action';
import { queueItem } from '@/lib/staff/queue';
import { newDemoState } from '@/lib/patient/demo-model';
const now = new Date('2026-10-14T08:00:00Z');
const d = newDemoState();
d.state.profile = {userId:d.userId,name:'Fictional QA',birthDate:'1980-04-15',biologicalSex:'female',locale:'en'};
d.state.assessment = {id:'qa-assessment',assessmentDate:'2026-10-09',answers:JSON.parse(fs.readFileSync('scripts/fixtures/patient-answers.json','utf8')),completedAt:'2026-10-09T08:00:00Z',revision:1,urgentRule:null};
const w = createWorkflow([],new Date('2026-10-09T08:00:00Z'));
assert.equal(queueItem(d.userId,d,w,now).overdue,true);
assert.equal(queueItem(d.userId,d,w,new Date('2026-10-13T19:59:00Z')).overdue,false);
assert.equal(queueItem(d.userId,d,w,new Date('2026-10-13T20:00:00Z')).overdue,true);
assert.match(serviceNextAction(w,now)!.title.en,/longer/);
w.consultation='required';
assert.equal(queueItem(d.userId,d,w,now).status,'consultation');
assert.equal(queueItem(d.userId,d,w,now).overdue,false);
assert.equal(serviceNextAction(w,now)!.kind,'appointment');
w.appointment={at:'2026-10-15T09:00:00+04:00',mode:'video',status:'scheduled'};
assert.equal(serviceNextAction(w,now)!.dueAt,w.appointment.at);
w.appointment.status='completed';
assert.equal(queueItem(d.userId,d,w,now).status,'review');
w.publication={at:now.toISOString(),doctor:'Fictional GP',version:1,resultTestIds:[],draft:w.draft};
assert.equal(queueItem(d.userId,d,w,now).status,'published');
assert.equal(queueItem(d.userId,d,w,now).owner,'None');
assert.equal(queueItem(d.userId,d,w,now).next,'Plan published; no review action currently due.');
const queueUi=fs.readFileSync('components/staff/case-queue.tsx','utf8');
assert.match(queueUi,/published:\s*"Published care"/);
assert.match(queueUi,/i\.owner === "None"[\s\S]*?"No review action currently due"/);
assert.equal(serviceNextAction(w,now),null);
d.state.assessment.completedAt=null;
assert.equal(queueItem(d.userId,d,w,now).status,'questions');
d.state.assessment.urgentRule='RF-01';
assert.equal(queueItem(d.userId,d,w,now).status,'urgent');
const tests=createWorkflow([{id:'a',title:'Fictional test',method:'lab',preparation:'Example',source:'QA'}]);
assert.equal(serviceNextAction(tests,now)!.kind,'tests');
tests.bookings=[{id:'b',testIds:['a'],at:'2026-10-15T09:00:00+04:00',mode:'clinic',address:'',status:'scheduled'}];
assert.equal(serviceNextAction(tests,now)!.title.en,'Your test requests are saved');
assert.equal(serviceNextAction(tests,now)!.title.hy,'Հետազոտությունների ձեր հայտերը պահպանված են');
tests.doctors=[];
assert.match(serviceNextAction(tests,now)!.title.en,/assignment/);
console.log('Work queue and next-step checks passed: urgent precedence, Armenia deadline boundary, weekend window, consultation, publication, booking and GP assignment.');
