import assert from 'node:assert/strict';
import React from 'react';
import {act,create,type ReactTestRenderer} from 'react-test-renderer';
import {NurseEscalation} from '@/components/staff/nurse-escalation';
import type {NurseHandoff} from '@/lib/nurse-chat/handoffs';
import type {NurseWorkspace} from '@/lib/nurse-chat/contracts';
(globalThis as unknown as {IS_REACT_ACT_ENVIRONMENT:boolean}).IS_REACT_ACT_ENVIRONMENT=true;
const id=(n:number)=>`ad130000-0000-4000-8000-${String(n).padStart(12,'0')}`;
let data:Extract<NurseWorkspace,{ok:true}>={ok:true,memberId:id(1),memberName:'Fictional member',doctorName:'Fictional doctor',version:1,canSend:false,items:[{id:'m1',text:'Fictional original message',at:'2026-10-31T08:00:00Z',senderName:'Member',senderRole:'member'}]};
const calls:NurseHandoff[]=[];let lost=true,code:string|undefined,saved=0;
const send=async(input:NurseHandoff)=>{calls.push(structuredClone(input));if(lost)throw Error('Response lost');return code?{ok:false,code}:{ok:true,taskId:id(3),replayed:true};};
const render=()=>React.createElement(NurseEscalation,{data,locale:'en',send,onSaved:()=>{saved++;}});
let tree!:ReactTestRenderer;
try{
 await act(async()=>{tree=create(render());});
 assert.equal(calls.length,0,'Reading does not create a handoff');
 assert.equal(tree.root.findAllByType('option').some(n=>n.props.value==='urgent'),false);
 await act(async()=>{tree.root.findAllByType('select')[0].props.onChange({target:{value:'m1'}});tree.root.findByType('textarea').props.onChange({target:{value:'  Review this exact observation  '}});});
 assert.ok(JSON.stringify(tree.toJSON()).includes('Fictional original message'));
 const submit=()=>tree.root.findByType('form').props.onSubmit({preventDefault(){}});
 await act(async()=>{submit();submit();});
 assert.equal(calls.length,1,'Same-event submits do not overlap');
 assert.equal(calls[0].messageId,'m1');assert.equal(calls[0].observation,'Review this exact observation');
 assert.equal(tree.root.findByType('fieldset').props.disabled,true,'Unknown outcome retains exact selection and observation');
 data={...data,version:2};await act(async()=>{tree.update(render());});
 assert.equal(tree.root.findByType('fieldset').props.disabled,true,'Reload cannot change an unknown pending request');
 lost=false;await act(async()=>submit());
 assert.deepEqual(calls[1],calls[0],'Exact replay retains old version, source, observation and request ID');assert.equal(saved,1);
 assert.equal(tree.root.findByType('textarea').props.value,'');
 await act(async()=>{tree.root.findAllByType('select')[0].props.onChange({target:{value:'m1'}});tree.root.findByType('textarea').props.onChange({target:{value:'Different observation'}});});
 code='stale_context';await act(async()=>submit());
 assert.equal(tree.root.findByType('fieldset').props.disabled,true,'Stale result needs a refreshed conversation');
 data={...data,version:3};await act(async()=>tree.update(render()));
 assert.equal(tree.root.findByType('fieldset').props.disabled,false);
 assert.equal(tree.root.findByType('textarea').props.value,'Different observation','Stale refusal retains unsaved text');
 code='already_exists';await act(async()=>submit());
 assert.equal(tree.root.findByType('fieldset').props.disabled,true);
 data={...data};await act(async()=>tree.update(render()));
 assert.equal(tree.root.findByType('fieldset').props.disabled,false,'Reload at the same conversation version recovers a duplicate or transient refusal');
 console.log('Nurse escalation UI: selected source, exact unknown-result retry, overlap guard, stale reload and no urgent routing passed (mocked IO).');
}finally{if(tree)await act(async()=>tree.unmount());}
