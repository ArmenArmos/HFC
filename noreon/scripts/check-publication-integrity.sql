begin;
create function pg_temp.check_true(ok boolean,msg text) returns void language plpgsql as $$ begin if ok is distinct from true then raise exception 'TEST: %',msg; end if; end $$;
do $$
declare c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid(); cl uuid:=gen_random_uuid(); r text:=gen_random_uuid()::text;
 s jsonb; w jsonb; draft jsonb; rec jsonb; ap jsonb; rev integer; ev bigint; saved jsonb; k text;
begin
 insert into auth.users(id) values(d);
 insert into public.workspace_clinics(id,name) values(cl,'Fictional test clinic');
 insert into public.workspace_staff(user_id,role,display_name,clinic_id) values(d,'doctor','Fictional doctor',cl);
 draft:='{"explanation":"Evidence checked","instructions":"Follow the reviewed instructions.","followUp":"","medicationName":"","medicationDose":"","medicationInstructions":"","medicationTimes":[]}';
 w:=jsonb_build_object('version',1,'revision',0,'startedAt','2026-10-11T00:00:00Z','questionnaireRevision',1,'tests','[]'::jsonb,'bookings','[]'::jsonb,'receivedTestIds','[]'::jsonb,'allResultsAt',now(),'consultation','not-required','appointment',null,'draft',draft,'draftSaved',false,'publication',null,'events','[]'::jsonb);
 s:=jsonb_build_object('version',1,'userId',c,'expiresAt',extract(epoch from now()+interval '1 day')*1000,'measurements','[]'::jsonb,'state',jsonb_build_object('consentAccepted',true,'profile',jsonb_build_object('userId',c,'name','Fictional','locale','en'),'assessment',jsonb_build_object('revision',1,'completedAt',now(),'urgentRule',null)));
 perform public.workspace_create_case(c,s,d);
 rev:=public.workspace_initialize_workflow(c,0,w);
 select evidence_revision into ev from public.workspace_cases where id=c;
 begin perform public.workspace_publish_review(c,d,rev,ev); raise exception 'TEST: unsaved draft published'; exception when others then if sqlerrm like 'TEST:%' then raise; end if; end;
 rev:=public.workspace_save_review_draft(c,d,rev,ev,draft);
 perform pg_temp.check_true((select draft_evidence_revision=ev from public.workspace_cases where id=c),'save evidence association');
 perform pg_temp.check_true(exists(select 1 from public.workspace_activity where case_id=c and kind='evidence.reviewed' and actor_id='staff:'||d),'review attribution');
 rev:=public.workspace_save_review_draft(c,d,rev,ev,draft);
 perform pg_temp.check_true((select count(*)=2 from public.workspace_activity where case_id=c and kind='evidence.reviewed' and actor_id='staff:'||d),'identical-text resave has its own attributed review event');
 rev:=public.workspace_publish_review(c,d,rev,ev);
 select state->'workflow'->'publication' into saved from public.workspace_cases where id=c;
 perform pg_temp.check_true(saved->'draft'=draft,'stored draft published');
 perform pg_temp.check_true((select evidence_revision=ev from public.workspace_cases where id=c),'publication must not bump evidence');
 rec:=jsonb_build_object('id',r,'user_id',c,'revision',0,'state','confirmed','reviewed',jsonb_build_object('rows','[]'::jsonb),'explanation',jsonb_build_object('summary','Checked'));
 perform public.workspace_write_report(c,r,'insert',null,rec);
 select record into rec from public.workspace_case_reports where case_id=c and id=r;
 perform pg_temp.check_true((select revision=rev and evidence_revision=ev+1 from public.workspace_cases where id=c),'report only increments evidence once');
 select evidence_revision into ev from public.workspace_cases where id=c;
 rev:=public.workspace_save_review_draft(c,d,rev,ev,draft);
 begin perform public.workspace_publish_review(c,d,rev,ev); raise exception 'TEST: unapproved report published'; exception when others then if sqlerrm not like '%approve every%' then raise; end if; end;
 ap:=jsonb_build_object('revision',0,'doctor','Fictional doctor','at',now(),'report',rec);
 perform public.workspace_write_report(c,r,'approve',0,null,ap,d);
 select evidence_revision into ev from public.workspace_cases where id=c;
 begin perform public.workspace_publish_review(c,d,rev,ev); raise exception 'TEST: stale saved evidence published'; exception when others then if sqlerrm like 'TEST:%' then raise; end if; end;
 perform pg_temp.check_true((select state#>'{workflow,publication}'=saved from public.workspace_cases where id=c),'failed publication preserves plan');
 rev:=public.workspace_save_review_draft(c,d,rev,ev,draft);
 rev:=public.workspace_publish_review(c,d,rev,ev);
 perform pg_temp.check_true((select published->'approval'=ap from public.workspace_case_reports where case_id=c and id=r),'approved snapshot published');
 perform pg_temp.check_true((select evidence_revision=ev from public.workspace_cases where id=c),'report publication does not bump evidence');
 -- Non-evidence updates and unaffected member revision after report changes.
 select state into s from public.workspace_cases where id=c;
 s:=jsonb_set(s,'{workflow,bookings}','[{"id":"fictional-booking","status":"scheduled"}]');
 rev:=public.workspace_save_case(c,rev,s);
 rev:=public.workspace_acknowledge_plan(c,rev,'workflow-plan-'||(s#>>'{workflow,publication,version}'));
 select state into s from public.workspace_cases where id=c;
 perform pg_temp.check_true((select evidence_revision=ev from public.workspace_cases where id=c),'bookings and care do not bump evidence');
 s:=jsonb_set(s,'{state,profile,locale}','"hy"');
 rev:=public.workspace_save_case(c,rev,s);
 perform pg_temp.check_true((select evidence_revision=ev from public.workspace_cases where id=c),'locale does not bump evidence');
 s:=jsonb_set(s,'{state,profile,name}','"Fictional corrected"');
 rev:=public.workspace_save_case(c,rev,s); ev:=ev+1;
 perform pg_temp.check_true((select evidence_revision=ev from public.workspace_cases where id=c),'identity bumps once');
 perform public.workspace_accept_reading(c,gen_random_uuid(),now(),120,80,null);
 select state,revision into s,rev from public.workspace_cases where id=c;ev:=ev+1;
 perform pg_temp.check_true((select evidence_revision=ev from public.workspace_cases where id=c),'BP bumps once');
 s:=jsonb_set(s,'{state,assessment,revision}','2');
 rev:=public.workspace_save_case(c,rev,s); ev:=ev+1;
 perform pg_temp.check_true((select evidence_revision=ev from public.workspace_cases where id=c),'assessment bumps once');
 s:=jsonb_set(s,'{workflow,tests}','[{"id":"a","title":"English","method":"lab"}]');
 rev:=public.workspace_save_case(c,rev,s); ev:=ev+1;
 s:=jsonb_set(s,'{workflow,tests,0,title}','"Translated"');
 rev:=public.workspace_save_case(c,rev,s);
 perform pg_temp.check_true((select evidence_revision=ev from public.workspace_cases where id=c),'translated test title is not new evidence');
 s:=jsonb_set(s,'{workflow,receivedTestIds}','["a","b"]');
 rev:=public.workspace_save_case(c,rev,s); ev:=ev+1;
 s:=jsonb_set(s,'{workflow,receivedTestIds}','["b","a"]');
 rev:=public.workspace_save_case(c,rev,s);
 perform pg_temp.check_true((select evidence_revision=ev from public.workspace_cases where id=c),'received ID order is irrelevant');
 s:=jsonb_set(s,'{state,consentAccepted}','false');
 rev:=public.workspace_save_case(c,rev,s); ev:=ev+1;
 perform pg_temp.check_true((select evidence_revision=ev from public.workspace_cases where id=c),'consent bumps once');
 s:=jsonb_set(s,'{workflow,allResultsAt}','null');
 rev:=public.workspace_save_case(c,rev,s); ev:=ev+1;
 perform pg_temp.check_true((select evidence_revision=ev from public.workspace_cases where id=c),'results readiness bumps once');
 perform pg_temp.check_true(exists(select 1 from public.workspace_evidence_changes where case_id=c and revision=ev and kind='allResultsAt'),'changed readiness logged');
 perform pg_temp.check_true(not has_table_privilege('service_role','public.workspace_cases','update'),'case writes restricted');
 perform pg_temp.check_true(not has_table_privilege('service_role','public.workspace_case_reports','update'),'report writes restricted');
 -- Parent-first owner maintenance is test setup only.
 perform 1 from public.workspace_cases where id=c for update;
 update public.workspace_cases set expires_at=now()-interval '1 second' where id=c;
 perform pg_temp.check_true(public.workspace_delete_expired_case(c),'expired case deletion');
 perform pg_temp.check_true(not exists(select 1 from public.workspace_evidence_changes where case_id=c),'cascade removes log without FK error');
end $$;
rollback;
