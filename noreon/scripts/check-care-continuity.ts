import assert from 'node:assert/strict';
import {newDemoState} from '@/lib/patient/demo-model';
import {createWorkflow,applyServiceCommand as apply,workflowCare} from '@/lib/service-workflow/model';
import {careAfterPublication,acknowledgeDemoPlan,recordDemoDose} from '@/lib/service-workflow/care-continuity';
const morning=new Date('2026-10-11T03:00:00Z'),now=new Date('2026-10-11T06:00:00Z');
let w=apply(createWorkflow([],morning),{type:'consultation',decision:'not-required'},morning);
const draft={...w.draft,instructions:'Fictional plan',medicationName:'Example',medicationDose:'Example dose',medicationTimes:['08:00']};
w=apply(w,{type:'save-draft',draft,evidenceRevision:0},morning);
w=apply(w,{type:'publish',evidenceRevision:0},morning);
const data=newDemoState();data.workflow=w;data.care={stage:'treatment',events:[],acknowledged:true};
const oldCare=data.care;
data.care=careAfterPublication(data.care,w.publication!);
assert.deepEqual(data.care.acknowledgements,[{planId:'workflow-plan-1',at:null}]);
assert.deepEqual(oldCare,{stage:'treatment',events:[],acknowledged:true},'transition does not mutate original');
acknowledgeDemoPlan(data,'workflow-plan-1',now);
assert.equal(data.care.acknowledgements![0].at,null,'legacy acknowledgement date remains unknown');
recordDemoDose(data,'workflow-plan-1',w.publication!.medicationOrderId!,'2026-10-11T04:00:00Z','taken',now,0);
assert.equal(data.care.events[0].planId,'workflow-plan-1');
const prior=data.workflow.publication!;
data.workflow=apply(apply(w,{type:'save-draft',draft:{...draft,explanation:'Updated only'},evidenceRevision:0},now),{type:'publish',evidenceRevision:0},now);
data.care=careAfterPublication(data.care,prior);
assert.equal(data.care.events.length,1);
assert.equal(workflowCare(data.workflow,data.care.events,data.care.acknowledgements!).plan!.acknowledged,false);
assert.throws(()=>acknowledgeDemoPlan(data,'workflow-plan-1',now),/changed/);
acknowledgeDemoPlan(data,'workflow-plan-2',now);
assert.equal(data.care.acknowledgements![1].at,now.toISOString());
acknowledgeDemoPlan(data,'workflow-plan-2',new Date('2026-10-11T07:00:00Z'));
assert.equal(data.care.acknowledgements!.length,2);
assert.equal(data.care.acknowledgements![1].at,now.toISOString());
assert.throws(()=>recordDemoDose(data,'workflow-plan-1',w.publication!.medicationOrderId!,'2026-10-11T04:00:00Z','taken',now,0),/changed/);
console.log('Care continuity: legacy unknown acknowledgement, version-specific idempotence, dose plan context and stale-plan rejection.');
const manyEvents=Array.from({length:120},(_,i)=>({medicationId:`prior-order-${i}`,planId:'workflow-plan-1',dueAt:'2026-10-10T04:00:00Z',recordedAt:'2026-10-10T04:00:00Z',status:'taken' as const}));
const preserved=careAfterPublication({stage:'treatment',events:manyEvents,acknowledged:false},prior);
assert.deepEqual(preserved.events,manyEvents,'publication cannot trim older check-ins');
recordDemoDose(data,'workflow-plan-2',w.publication!.medicationOrderId!,'2026-10-11T04:00:00Z','skipped',now,0);
assert.equal(data.care.events[0].planId,'workflow-plan-1','correction retains original plan context');
