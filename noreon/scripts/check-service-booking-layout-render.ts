import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import * as React from 'react';
import * as jsx from 'react/jsx-runtime';
import * as icons from 'lucide-react';
import {renderToStaticMarkup} from 'react-dom/server';
import {testTitle} from '@/lib/patient/catalogue-label';
import * as common from '@/components/patient-care/common';
import * as model from '@/lib/service-workflow/model';
import * as reconciliation from '@/lib/service-workflow/reconciliation';
import {armeniaDate} from '@/lib/patient-care/model';
import {BookingPreparation} from '@/components/service-workflow/booking-preparation';
import type {ServiceWorkflow} from '@/lib/service-workflow/types';
import * as realLocaleModule from '@/lib/locale';
const exports: {ServiceBooking?: React.ComponentType<{workflow:ServiceWorkflow;locale:'en'|'hy'}>}={};
const code=ts.transpileModule(readFileSync('components/service-workflow/client.tsx','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}}).outputText;
vm.runInNewContext(code,{exports,process,Date,require:(name:string)=>{
  if(name==='react/jsx-runtime') return jsx;
  if(name==='react') return React;
  if(name==='lucide-react') return icons;
  if(name==='@/lib/patient/catalogue-label') return {testTitle};
  if(name.endsWith('/common')) return common;
  if(name.endsWith('/reconciliation')) return reconciliation;
  if(name==='@/lib/service-workflow/model') return model;
  if(name==='@/lib/patient-care/model') return {armeniaDate};
  if(name==='./booking-preparation') return {BookingPreparation};
  if(name==='./shared') return {useWorkflowCommand:()=>({run(){},pending:false,error:''}),ActionError:()=>null,SlotFields:()=>React.createElement('input',{name:'day',type:'date'}),buttonClass:'',quietClass:'',inputClass:'',formTime(){}};
  if(name==='@/lib/locale')return realLocaleModule;throw new Error(`Unexpected boundary ${name}`);
}});
const now=new Date();
const slot=armeniaDate(new Date(now.getTime()+7*86400000))+'T09:00:00+04:00';
const tests=[{id:'one',title:'First lab',method:'lab' as const,preparation:'',source:'demo'}];
const booked=model.applyServiceCommand(model.createWorkflow(tests,now),{type:'book',testIds:['one'],at:slot,mode:'home',address:'Fixture address'},now);
const render=(workflow:ServiceWorkflow)=>renderToStaticMarkup(React.createElement(exports.ServiceBooking!,{workflow,locale:'en'}));
const bookedHtml=render(booked);
assert.doesNotMatch(bookedHtml,/Manage tests and appointment/,'The service page must not link to itself as a progress action');
assert.doesNotMatch(bookedHtml,/<h2[^>]*>Arrange your tests<\/h2>/,'All-booked cases must lead with booking facts, not an empty arrangement card');
assert.match(bookedHtml,/Your test requests/);
assert.match(bookedHtml,/Tests \(1\)/);
assert.ok(bookedHtml.indexOf('Fixture address')<bookedHtml.indexOf('Your assigned GP'));
assert.match(bookedHtml,/<details[^>]*><summary[^>]*>Your assigned GP/,'Non-actionable GP information starts collapsed');
assert.match(bookedHtml,/<details[^>]*><summary[^>]*>Previous reports/);
const unbookedHtml=render(model.createWorkflow(tests,now));
assert.match(unbookedHtml,/<h2[^>]*>Arrange your tests<\/h2>/);
assert.match(unbookedHtml,/<form/,'Unbooked tests retain their arrangement form');
assert.match(render({...booked,recommendationsPending:true}),/Complete your questions/);
assert.match(render(model.createWorkflow([],now)),/No additional tests are listed/);
const requiredHtml=render({...booked,consultation:'required'});
assert.match(requiredHtml,/Book GP appointment/,'Actionable GP booking retains its form');
assert.doesNotMatch(requiredHtml,/<summary[^>]*>Your assigned GP/);
console.log('Actual ServiceBooking layout: booked-first, no self-link/empty form, collapsed secondary information, unbooked/incomplete/no-test states, and actionable GP form passed. Action/router boundaries mocked.');

const catalogue=model.createWorkflow([{id:'lipid-panel',title:'Lipid profile with LDL-C',method:'lab',preparation:'',source:'demo'},{id:'unknown-catalogue',title:'Provider supplied title',method:'lab',preparation:'',source:'demo'}],now);
const original=JSON.stringify(catalogue);
const localized=renderToStaticMarkup(React.createElement(exports.ServiceBooking!,{workflow:catalogue,locale:'hy'}));
assert.match(localized,/Լիպիդային պրոֆիլ և LDL-C/,'Known current catalogue labels use existing approved Armenian seed copy');
assert.doesNotMatch(localized,/Lipid profile with LDL-C/);
assert.match(localized,/Provider supplied title/,'Unknown catalogue labels retain source text');
assert.equal(JSON.stringify(catalogue),original,'Translation must not alter workflow titles, IDs or context');
const custom=model.createWorkflow([{id:'lipid-panel',title:'Provider custom lipid title',method:'lab',preparation:'',source:'demo'}],now);
assert.match(renderToStaticMarkup(React.createElement(exports.ServiceBooking!,{workflow:custom,locale:'hy'})),/Provider custom lipid title/,'Provider-authored title stays intact even for a known ID');
const historical=model.applyServiceCommand(catalogue,{type:'book',testIds:['lipid-panel'],at:slot,mode:'home',address:'Fixture address'},now);
historical.bookings[0].testSnapshots![0].title='Recorded snapshot title';
assert.match(renderToStaticMarkup(React.createElement(exports.ServiceBooking!,{workflow:historical,locale:'hy'})),/Recorded snapshot title/,'Historical snapshot titles retain their recorded wording');
console.log('Current catalogue HY presentation, unknown/provider fallback and unchanged snapshot/workflow passed.');
