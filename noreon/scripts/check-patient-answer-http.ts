import assert from "node:assert/strict";
import { createPatientAnswerHandler } from "@/lib/patient/answer-http";
import type { PatientState, PatientProfile } from "@/lib/patient/types";
const profile: PatientProfile = {userId:"owner",name:"QA",birthDate:"1980-01-01",biologicalSex:"male",locale:"en"};
const state: PatientState = {profile,consentAccepted:true,assessment:{id:"assessment",revision:1,assessmentDate:"2026-10-13",answers:{},completedAt:null,urgentRule:null}};
let writes = 0;
const store = () => ({read:async()=>state,profile:async()=>0,assessment:async()=>{writes++;return 2;},measurement:async()=>{}});
const handle = createPatientAnswerHandler({user:async()=>({userId:"owner",phone:"+37499000000"}),store});
const input={expectedAssessmentId:"assessment",expectedRevision:1,entries:[{fieldId:"q6.conditions",value:"unknown"}]};
const request=(body:unknown=input,origin="https://noreon.test",contentType="application/json")=>new Request("https://noreon.test/patient/answers",{method:"POST",headers:{origin,"content-type":contentType},body:typeof body==="string"?body:JSON.stringify(body)});
assert.equal((await handle(request(input,"https://other.test"))).status,403);
assert.equal((await handle(request(input,""))).status,403);
assert.equal((await handle(request(input,"https://noreon.test","text/plain"))).status,415);
assert.equal((await handle(request("{bad"))).status,400);
assert.equal((await handle(request(" ".repeat(16001)))).status,413,"Actual bytes are capped regardless Content-Length");
assert.equal((await handle(request({...input,expectedAssessmentId:undefined}))).status,400);
assert.equal((await handle(request({...input,expectedAssessmentId:"another-assessment"}))).status,409);
assert.equal((await handle(request({...input,entries:[{fieldId:"q6.conditions",value:["none","diabetes"]}]}))).status,400,"Clinical validation still rejects mixed exclusive answers");
assert.equal(writes,0,"Rejected requests never write");
const denied=createPatientAnswerHandler({user:async()=>null,store:()=>{throw Error("Signed out must not access a store");}});
assert.equal((await denied(request())).status,401);
const accepted=await handle(request());
assert.equal(accepted.status,200);
assert.equal(accepted.headers.get("cache-control"),"no-store");
assert.deepEqual(await accepted.json(),{ok:true,revision:2});
assert.equal(writes,1);
console.log("Fixed answer endpoint requires same-origin JSON, capped payload, owned assessment/revision and clinical validation; signed-out and invalid requests cannot write.");
