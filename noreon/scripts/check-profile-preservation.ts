import assert from 'node:assert/strict';
import fs from 'node:fs';
import {normalizeSharedWorkflow} from '@/lib/service-workflow/normalization';
import {clinicalContext} from '@/lib/service-workflow/reconciliation';
import {buildPlan,evaluate} from '@/lib/clinical/rules/engine';
import { newDemoState, demoStoreFor } from '@/lib/patient/demo-model';
import { createPatientService } from '@/lib/patient/service';
import { createWorkflow, applyServiceCommand } from '@/lib/service-workflow/model';
const data = newDemoState();
const store = demoStoreFor(data, async state => { normalizeSharedWorkflow(state); });
const service = createPatientService({ user: async () => ({ userId: data.userId, phone: '+37499000000' }), store: () => store });
const profile = { name: 'Fictional preservation check', birthDate: '1974-05-18', biologicalSex: 'male' as const, locale: 'en' as const };
await service.saveProfile(profile, true);
await store.assessment(data.userId, 0, JSON.parse(fs.readFileSync('scripts/fixtures/patient-answers.json','utf8')), true, null);
const now = new Date('2026-10-10T05:00:00Z');
// The fixture is treated hypertension, so the current engine's plan is the hypertension workup
// (tests-vs-tree audit A3). Seed that plan so only the profile edit can change the workflow.
const plan = buildPlan(evaluate({ answers: data.state.assessment!.answers, observations: [] }));
let w = createWorkflow(plan.map(t => ({ id: t.id, title: t.name.en ?? t.name.hy, method: t.method === 'blood_draw' || t.method === 'urine_sample' ? 'lab' as const : t.method === 'home_log' ? 'home-log' as const : 'clinic' as const, preparation: 'Provider confirmation required', source: 'fictional' })), now);
w.questionnaireRevision = data.state.assessment!.revision;
w.clinicalContext = clinicalContext(data.state);
for (const method of ['lab', 'clinic'] as const) w = applyServiceCommand(w, {type:'book', testIds:w.tests.filter(t=>t.method===method).map(t=>t.id), at:'2026-10-13T09:00:00+04:00', mode:'clinic', address:''}, now);
w = applyServiceCommand(w, {type:'receive', testIds:w.tests.map(t=>t.id)}, now);
w = applyServiceCommand(w, {type:'consultation', decision:'not-required'}, now);
w = applyServiceCommand(w, {type:'save-draft',draft:{...w.draft,instructions:'Reviewed instructions.'},evidenceRevision:w.evidenceRevision ?? 0}, now);
w = applyServiceCommand(w, {type:'publish',evidenceRevision:w.evidenceRevision ?? 0}, now);
data.workflow = w;
const before = structuredClone(data);
assert.equal((await service.saveProfile({...profile, locale:'hy', name:'Renamed fictional member'}, true)).ok, true);
assert.equal(data.state.assessment!.revision, before.state.assessment!.revision, 'Language/name edits must not invalidate questionnaire-bound workflow');
assert.deepEqual(data.state.assessment, before.state.assessment, 'Presentation edits must leave clinical assessment untouched');
assert.deepEqual(data.workflow, before.workflow, 'Publication, bookings, consultation, events and draft must survive');
assert.equal((await service.saveProfile({...profile, birthDate:'1973-05-18'}, true)).ok, true);
assert.equal(data.workflow!.questionnaireRevision, data.state.assessment!.revision, 'A demographic correction must not silently discard the existing care workflow');
assert.equal(data.state.assessment!.completedAt, before.state.assessment!.completedAt, 'A valid demographic correction must keep completed care actionable');
assert.equal(data.workflow!.consultation,'undecided','changed clinical demographics require reconsidering the consultation decision');
assert.deepEqual(data.workflow!.publication, before.workflow!.publication);
assert.deepEqual(data.workflow!.bookings, before.workflow!.bookings);
console.log('Profile edits preserve assessment on language/name changes and retain published care on demographic corrections.');
