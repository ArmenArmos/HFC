import assert from 'node:assert/strict';
import { createWorkflow, applyServiceCommand as apply } from '@/lib/service-workflow/model';
const now = new Date('2026-10-11T10:00:00Z');
const ready = apply(createWorkflow([], now), { type: 'consultation', decision: 'not-required' }, now);
// A direct command must not publish the untouched initial draft.
assert.throws(() => apply(ready, { type: 'publish' }, now), /save|draft/i);
const future = { ...ready, consultation: 'required' as const,
  appointment: { at: '2026-10-12T10:00:00Z', mode: 'video' as const, status: 'scheduled' as const } };
assert.throws(() => apply(future, { type: 'complete-consultation' }, now), /time|started|future/i);
const missingDoctor = { ...ready, doctors: [], assignedDoctorId: '' };
assert.throws(() => apply(missingDoctor, {type:'publish'}, now), /doctor|GP/i);
console.log('Publication integrity: unsaved draft, future consultation and missing doctor rejected.');
const draft = {...ready.draft, explanation:'Checked current evidence.', instructions:'Follow the reviewed plan.'};
const saved = apply(ready, {type:'save-draft',draft,evidenceRevision:0}, now);
assert.equal(saved.draftEvidenceRevision,0);
const publication = apply(saved,{type:'publish',evidenceRevision:0},now);
assert.equal(publication.publication?.draft.instructions,'Follow the reviewed plan.');
assert.throws(() => apply({...saved,evidenceRevision:1},{type:'publish',evidenceRevision:1},now), /evidence/i);
assert.throws(() => apply(saved,{type:'publish',evidenceRevision:0,reportEvidenceRevision:1},now), /evidence/i);
assert.throws(() => apply(saved,{type:'save-draft',draft,evidenceRevision:1},now), /evidence/i);
assert.throws(() => apply(ready,{type:'save-draft',draft:{...draft,medicationName:'Example',medicationDose:''},evidenceRevision:0},now), /valid/i);
const past = {...future,appointment:{...future.appointment,at:'2026-10-11T09:00:00Z'}};
const completed = apply(past,{type:'complete-consultation'},now);
assert.equal(completed.appointment?.completedAt,'2026-10-11T10:00:00.000Z');
assert.equal(completed.appointment?.completedBy,past.assignedDoctorId);
const {normalizeSharedWorkflow} = await import('@/lib/service-workflow/normalization');
const {newDemoState} = await import('@/lib/patient/demo-model');
const state = newDemoState();
state.state.profile={userId:state.userId,name:'Fictional',birthDate:'1980-01-01',biologicalSex:'male',locale:'en'};
state.state.consentAccepted=true;
state.state.assessment={id:'fictional',revision:2,answers:{},assessmentDate:'2026-10-11',completedAt:null,urgentRule:null};
state.workflow=publication;
state.care={stage:'treatment',events:[],acknowledged:false};
assert.equal(normalizeSharedWorkflow(state),true);
assert.deepEqual(state.workflow.publication,publication.publication);
assert.equal(state.workflow.startedAt,publication.startedAt);
assert.equal(state.workflow.questionnaireRevision,2);
assert.deepEqual(state.workflow.tests,[]);
assert.equal(state.workflow.allResultsAt,null, "Restart must clear the all-results date");
assert.equal(normalizeSharedWorkflow(state),false);
console.log('Publication integrity: valid save/publish, stale evidence, report edits, medication validity, attestation and retained publication through normalization passed.');
const {workflowCare}=await import('@/lib/service-workflow/model');
const {careActions}=await import('@/lib/patient-care/model');
state.workflow.publication={...publication.publication!,resultTestIds:['lipid-panel'],draft:{...draft,medicationName:'Fictional existing medicine',medicationDose:'Existing example dose',medicationTimes:['08:00']}};
state.care.acknowledged=true;
state.care.events=[{medicationId:'workflow-medication-1',dueAt:'2026-10-11T04:00:00Z',recordedAt:now.toISOString(),status:'taken'}];
const retainedCare=workflowCare(state.workflow,state.care.events,true);
state.state.assessment={...state.state.assessment!,revision:3,completedAt:now.toISOString(),urgentRule:'RF-01'};
assert.equal(normalizeSharedWorkflow(state),true);
const urgentCare=workflowCare(state.workflow,state.care.events,state.care.acknowledged);
assert.deepEqual(urgentCare.plan,retainedCare.plan);
assert.deepEqual(urgentCare.results,retainedCare.results);
assert.deepEqual(urgentCare.events,retainedCare.events);
assert.equal(careActions(urgentCare,{urgent:true,complete:true,measuredToday:false,now})[0].kind,'urgent');
console.log('Urgent questionnaire normalization keeps the published plan, results, medication routine and dose events available; urgent guidance takes first priority.');
const legacy=newDemoState();legacy.state.profile=state.state.profile;legacy.state.consentAccepted=true;
legacy.workflow=createWorkflow([{id:'fictional-fallback',title:'Legacy fallback',method:'lab',preparation:'',source:'demo'}],now);
assert.equal(normalizeSharedWorkflow(legacy),true,'missing assessment must remove legacy fallback tests even when both questionnaire revisions are undefined');
assert.deepEqual(legacy.workflow.tests,[]);assert.equal(legacy.workflow.allResultsAt,null);
assert.equal(normalizeSharedWorkflow(legacy),false,'normalized empty workflow is stable');
