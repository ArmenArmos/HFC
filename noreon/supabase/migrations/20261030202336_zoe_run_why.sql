-- Zoe's why record (Khikar 30 Oct, lib/zoe/why.ts): one structured snapshot per run of why Zoe did what she did, generated
-- rationale and never a doctor's reasoning. It lives on the run, so it goes with the run when the account is deleted, and
-- zoe_runs already has RLS on with no policy and no direct grants: nothing here adds a member-readable path.
--
-- 1. zoe_runs.why, written once by the worker after the run finished. A failed save never touches the answer: the run simply
--    has no record, and the read says so.
-- 2. zoe_run_why, the one read: the member's assigned active doctor, or an admin (the trace screen; zoe_run_detail already gives
--    admins the run's redacted input and output). Every read is one access_audit row in the same transaction. A nurse does not
--    read it: nurses do not read member conversations today (zoe_runs_for_doctor, conversation_workspace), and the record
--    quotes them. Staff Zoe's future tool calls this function with the staff user's JWT, never the service role.

alter table public.zoe_runs add column why jsonb
 constraint zoe_runs_why_shape check(why is null or(jsonb_typeof(why)='object'and why->>'v'='1'and octet_length(why::text)<=32768));
comment on column public.zoe_runs.why is
 'Generated rationale for this run (lib/zoe/why.ts): a snapshot written once, redacted like the summary. Staff only, through zoe_run_why. Not a doctor''s reasoning.';

-- A snapshot stays what it was, whatever writes to the run later.
create function public._zoe_run_why_once()returns trigger language plpgsql set search_path=''as $$
begin
 if old.why is not null then raise exception using errcode='55000',message='A saved why record does not change';end if;
 return new;
end$$;
create trigger zoe_run_why_once before update of why on public.zoe_runs for each row when(old.why is distinct from new.why)execute function public._zoe_run_why_once();
revoke all on function public._zoe_run_why_once()from public,anon,authenticated,service_role;

-- The worker's write: once per run, and a bad record is refused with a code, never an error the worker has to survive.
create function public.zoe_run_why_record(p_run uuid,p_why jsonb)returns jsonb
language plpgsql security definer set search_path=''as $$
begin
 if jsonb_typeof(p_why)is distinct from 'object'or p_why->>'v'is distinct from '1'or octet_length(p_why::text)>32768 then
  return jsonb_build_object('ok',false,'code','why_invalid');end if;
 update public.zoe_runs set why=p_why where id=p_run and why is null;
 if not found then return jsonb_build_object('ok',false,'code','why_not_recorded');end if;
 return jsonb_build_object('ok',true);
end$$;

-- The one read. An unknown run and someone else's run refuse the same way, so the function says nothing about which runs exist.
create function public.zoe_run_why(p_run uuid)returns jsonb
language plpgsql security definer set search_path=''as $$
declare a uuid:=auth.uid();r public.zoe_runs;
begin
 if auth.role()is distinct from 'authenticated'or a is null then raise insufficient_privilege;end if;
 select * into r from public.zoe_runs where id=p_run;
 if a is not distinct from r.member_id then raise insufficient_privilege;end if;
 if exists(select 1 from public.workspace_staff s where s.user_id=a and s.role='admin')then perform public._real_staff_require_admin();
 else perform public._assigned_active_doctor(r.member_id);end if;
 if r.id is null then raise insufficient_privilege;end if;
 perform public._access_audit_record(r.member_id,'zoe_run_why',r.id::text);
 return jsonb_build_object('ok',true,'label','Generated by Zoe from fixed rules and AI. This is not a doctor''s reasoning.',
  'run',jsonb_build_object('id',r.id,'memberId',r.member_id,'messageSeq',r.message_seq,'kind',r.kind,'outcome',r.outcome,'reason',r.reason_code,'finishedAt',r.finished_at),'why',r.why);
end$$;

revoke all on function public.zoe_run_why_record(uuid,jsonb),public.zoe_run_why(uuid)from public,anon,authenticated,service_role;
grant execute on function public.zoe_run_why_record(uuid,jsonb)to service_role;
grant execute on function public.zoe_run_why(uuid)to authenticated;
